/** Six characters of hex with a hash. Swatches are offered; typing is allowed. */
const hexColour = z
  .string()
  .trim()
  .regex(/^#[0-9a-fA-F]{6}$/, 'Colour must be a six-digit hex like #A95031')
  .transform((value) => value.toUpperCase())

export const categoryWriteSchema = z.object({
  id: z.uuid(),
  name: z.string().trim().min(1, 'Name the category').max(60),
  icon: z.string().trim().min(1).max(60),
  colour_hex: hexColour,
  default_bucket: z.enum(['life', 'car_running', 'car_project']),
  default_counts_toward_budget: z.boolean(),
  sort_order: z.number().int().nullable().default(null),
})

export type CategoryWrite = z.infer<typeof categoryWriteSchema>

export const categoryArchiveSchema = z.object({
  id: z.uuid(),
  archived: z.boolean(),
})
