/**
 * One zod schema per entity, shared client and server (CLAUDE.md section 2).
 *
 * The server actions parse untrusted input with these; the form validates the
 * same shape before it ever calls one, so the two can never disagree about what
 * a valid expense is.
 */

import { z } from 'zod'

const ISO_DATE = /^\d{4}-\d{2}-\d{2}$/

const isoDate = z
  .string()
  .regex(ISO_DATE, 'Date must be YYYY-MM-DD')
  .refine((value) => !Number.isNaN(Date.parse(value)), 'That is not a real date')

/** Trim, then treat an empty string as absent. Forms hand back '' , not null. */
const optionalText = (max: number) =>
  z
    .string()
    .trim()
    .max(max)
    .transform((value) => (value === '' ? null : value))
    .nullable()
    .default(null)

const optionalUuid = z
  .union([z.uuid(), z.literal('')])
  .transform((value) => (value === '' ? null : value))
  .nullable()
  .default(null)

/**
 * A foreign key the form may or may not know about.
 *
 * Absent is not the same as null here. The mark-installed flow sends
 * `mod_plan_id` and the ledger's edit form does not, and an edit that quietly
 * shipped `null` for a field it never displayed would unlink an expense from the
 * mod it paid for the first time somebody fixed a typo in the merchant. So this
 * one is optional rather than defaulted, and the action leaves the column alone
 * when it is missing.
 */
const linkedUuid = z
  .union([z.uuid(), z.literal('')])
  .transform((value) => (value === '' ? null : value))
  .nullable()
  .optional()

/**
 * Money is a whole number of minor units and is never zero: an expense of
 * nothing is a mistake, not a record. Negative is allowed and meaningful —
 * a refund, or a part sold on.
 */
const minorAmount = z
  .number()
  .int('Amount must be a whole number of minor units')
  .refine((value) => Number.isSafeInteger(value), 'Amount is out of range')
  .refine((value) => value !== 0, 'Enter an amount')

export const expenseWriteSchema = z
  .object({
    /**
     * Generated by the client so the optimistic row and the stored row are the
     * same row. A duplicate id is rejected by the primary key, which is the
     * behaviour we want if a submit is somehow replayed.
     */
    id: z.uuid(),
    occurred_on: isoDate,
    amount: minorAmount,
    currency: z.string().length(3).toUpperCase(),
    category_id: optionalUuid,
    vehicle_id: optionalUuid,
    bucket: z.enum(['life', 'car_running', 'car_project']),
    counts_toward_budget: z.boolean(),
    amortize_months: z.number().int().min(1).max(120),
    merchant: optionalText(160),
    note: optionalText(2000),
    odometer_km: z.number().int().min(0).max(9_999_999).nullable().default(null),
    mod_plan_id: linkedUuid,
    /**
     * The sinking fund this was paid out of, which is what
     * docs/01-PRODUCT.md calls being flagged `funded_from_fund`. Set only by
     * the mark-installed flow, and only on a create: setting it is what draws
     * the fund down, so an edit that carried it would draw it down twice.
     * Absent means "do not touch", the same as `mod_plan_id`.
     */
    fund_id: linkedUuid,
  })
  .refine(
    (value) => (value.bucket === 'life' ? value.vehicle_id === null : value.vehicle_id !== null),
    {
      message: 'A car bucket needs a vehicle, and life spend cannot have one',
      path: ['bucket'],
    },
  )
  .refine((value) => value.odometer_km === null || value.vehicle_id !== null, {
    message: 'An odometer reading needs a vehicle',
    path: ['odometer_km'],
  })

export type ExpenseWrite = z.infer<typeof expenseWriteSchema>

export const expenseIdSchema = z.uuid()

